/** Emit the worker's plain ESM from the shared typed geometry implementation. */
import fs from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {fileURLToPath,pathToFileURL} from 'node:url';
import ts from 'typescript';

export const returnSearchSource=fileURLToPath(new URL('../../src/lib/geometry/returnSearch.ts',import.meta.url));
export const returnSearchOutput=fileURLToPath(new URL('../../static/inverse/core/return-search.js',import.meta.url));

export async function buildReturnSearch({check=false}={}){
  const source=await fs.readFile(returnSearchSource,'utf8');
  const digest=createHash('sha256').update(source).digest('hex');
  const result=ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2023,module:ts.ModuleKind.ESNext},reportDiagnostics:true});
  if(result.diagnostics?.length)throw new Error(ts.formatDiagnosticsWithColorAndContext(result.diagnostics,{getCurrentDirectory:()=>process.cwd(),getNewLine:()=> '\n',getCanonicalFileName:file=>file}));
  // This shared module must not pull the inverse engine into the editor bundle.
  const syntax=ts.createSourceFile(returnSearchSource,source,ts.ScriptTarget.Latest,true);
  if(syntax.statements.some(s=>ts.isImportDeclaration(s)||ts.isExportDeclaration(s)&&s.moduleSpecifier))throw new Error('Return geometry must be standalone.');
  const output=`// Generated by scripts/inverse/build-return-search.mjs; edit src/lib/geometry/returnSearch.ts.\n// Source SHA-256: ${digest}; TypeScript ${ts.version}.\n`+result.outputText;
  if(check){if(await fs.readFile(returnSearchOutput,'utf8')!==output)throw new Error('Worker geometry is stale. Run node scripts/inverse/build-return-search.mjs.');}
  else await fs.writeFile(returnSearchOutput,output);
  return{sourceSha256:digest,bytes:Buffer.byteLength(output),typescript:ts.version};
}
if(process.argv[1]&&import.meta.url===pathToFileURL(process.argv[1]).href)console.log(await buildReturnSearch({check:process.argv.includes('--check')}));
