/** The top-level declaration of `text` starting with the line `head`: a function through its first line closing
 * it at the top level (`}`), constants through their first line ending in `;`. Throws when it is not there once. */
function declaration(text, head) {
  const lines = text.split('\n'), at = lines.flatMap((line, k) => (line.startsWith(head) ? [k] : []));
  if (at.length !== 1) throw new Error(`${head}: found ${at.length} times`);
  const ends = /\bfunction\b/.test(head) ? line => line === '}' : line => /;$/.test(line);
  let end = at[0];
  while (!ends(lines[end])) end++;
  return lines.slice(at[0], end + 1).join('\n');
}
